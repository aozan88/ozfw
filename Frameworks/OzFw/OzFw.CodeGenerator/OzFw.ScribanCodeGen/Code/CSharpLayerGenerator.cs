using OzFw.ScribanCodeGen.Model;
using OzFw.ScribanCodeGen.Sql;
using Scriban;
using Scriban.Runtime;

namespace OzFw.ScribanCodeGen.Code
{
    /// <summary>
    /// Normalize edilmiş modelden C# katmanlarını Templates/Layers/*.sbn şablonlarıyla üretir.
    /// *.g.cs dosyaları her çalıştırmada yeniden üretilir; Scaffold=true dosyalar (csproj, Program.cs,
    /// DbContext, servis constructor'ı ...) yalnızca yoksa oluşturulur ve sonra geliştiriciye aittir.
    /// Klasör/namespace düzeni mevcut Ortak/Sistem modülleriyle aynıdır.
    /// </summary>
    public static class CSharpLayerGenerator
    {
        public const int DefaultApiPort = 24300;

        /// <summary>
        /// .g.cs dosyalarının başlığı. CLI, bu başlıkla başlamayan bir .g.cs dosyasının üzerine yazmaz.
        /// &lt;auto-generated&gt; dosyalarda derleyici nullable bağlamını kapattığı için #nullable enable eklenir.
        /// </summary>
        public const string GeneratedMarker = "// <auto-generated>";

        public const string GeneratedHeader =
            GeneratedMarker + "\n" +
            "//     OzFw.ScribanCodeGen tarafından modelden üretildi. Elle düzenlemeyin; değişiklikler yeniden üretimde kaybolur.\n" +
            "//     Özelleştirme için aynı partial sınıfı .g.cs olmayan ayrı bir dosyada genişletin.\n" +
            "// </auto-generated>\n" +
            "#nullable enable\n\n";

        public static IReadOnlyList<GeneratedFile> Generate(CodeGenModel model, int apiPort = DefaultApiPort, string? templatesDir = null)
        {
            var unsupported = model.Entities
                .SelectMany(e => e.Fields.Where(f => f.Type == TypeMap.Geometry).Select(f => $"{e.Name}.{f.Name}"))
                .ToList();
            if (unsupported.Count > 0)
                throw new ModelValidationException(unsupported
                    .Select(f => $"'{f}': Geometry alanları C# şablonlarında henüz desteklenmiyor (yalnızca --only sql ile üretilebilir).")
                    .ToList());

            var m = ModuleView.From(model, apiPort);
            var templates = new TemplateSet(templatesDir ?? Path.Combine(AppContext.BaseDirectory, "Templates", "Layers"));
            var files = new List<GeneratedFile>();

            void Gen(string template, string path, EntityView? e = null) =>
                files.Add(new GeneratedFile(path, GeneratedHeader + templates.Render(template, m, e)));
            void Scaffold(string template, string path, EntityView? e = null) =>
                files.Add(new GeneratedFile(path, templates.Render(template, m, e), Scaffold: true));

            var p = m.Paths;
            foreach (var e in m.Entities)
            {
                Gen("entity", $"{p.Domain}/{m.Name}Entities/{e.Name}.g.cs", e);
                Gen("dto", $"{p.Dtos}/{m.Name}Dtos/{e.Name}Dto.g.cs", e);
                Gen("irepository", $"{p.Application}/Contract/I{e.Name}Repository.g.cs", e);
                Gen("iservice", $"{p.Application}/Business/I{e.Name}Servis.g.cs", e);
                Gen("service", $"{p.Application}/Business/{e.Name}Servis.g.cs", e);
                Scaffold("service_stub", $"{p.Application}/Business/{e.Name}Servis.cs", e);
                Gen("validation", $"{p.Application}/Validations/{e.Name}DtoValidation.g.cs", e);
                Gen("entity_config", $"{p.Data}/Persistence/Configurations/{e.Name}Configuration.g.cs", e);
                Gen("repository", $"{p.Data}/Repositories/{e.Name}Repository.g.cs", e);
                Gen("controller", $"{p.Api}/Controllers/{e.Name}Controller.g.cs", e);
            }

            Gen("base_columns", $"{p.Data}/Persistence/Configurations/BaseEntityColumns.g.cs");
            Gen("dbcontext_g", $"{p.Data}/Persistence/{m.Name}DbContext.g.cs");
            Gen("data_registration", $"{p.Data}/Registration/{m.Name}DataRegistration.g.cs");
            Gen("app_registration", $"{p.Application}/Registration/{m.Name}ApplicationRegistration.g.cs");
            Gen("generated_mappings", $"{p.Application}/Mappings/GeneratedMappings.g.cs");

            Scaffold("dbcontext_stub", $"{p.Data}/Persistence/{m.Name}DbContext.cs");
            Scaffold("mapster_stub", $"{p.Application}/Mappings/MapsterConfig.cs");
            Scaffold("application_csproj", $"{p.Application}/{m.ProjectPrefix}.Application.csproj");
            Scaffold("data_csproj", $"{p.Data}/{m.ProjectPrefix}.Data.csproj");
            Scaffold("api_csproj", $"{p.Api}/{m.ProjectPrefix}.API.csproj");
            Scaffold("api_project_stub", $"{p.Api}/Extensions/{m.Name}ApiProject.cs");
            Scaffold("program_stub", $"{p.Api}/Program.cs");
            Scaffold("launchsettings", $"{p.Api}/Properties/launchSettings.json");
            Scaffold("appsettings", $"{p.Api}/appsettings.json");
            Scaffold("appsettings_dev", $"{p.Api}/appsettings.Development.json");

            return files;
        }

        /// <summary>Yeni oluşturulan modül csproj'ları (sln'e eklenmek üzere).</summary>
        public static IEnumerable<string> ProjectFiles(IEnumerable<GeneratedFile> files) =>
            files.Where(f => f.Scaffold && f.RelativePath.EndsWith(".csproj", StringComparison.OrdinalIgnoreCase)).Select(f => f.RelativePath);

        private sealed class TemplateSet
        {
            private readonly string _dir;
            private readonly Dictionary<string, Template> _cache = new();

            public TemplateSet(string dir) => _dir = dir;

            public string Render(string name, ModuleView module, EntityView? entity)
            {
                if (!_cache.TryGetValue(name, out var template))
                {
                    var path = Path.Combine(_dir, name + ".sbn");
                    if (!File.Exists(path))
                        throw new FileNotFoundException($"Şablon bulunamadı: {path}");
                    template = Template.Parse(File.ReadAllText(path), path);
                    if (template.HasErrors)
                        throw new InvalidOperationException($"Şablon hatalı ({name}): {string.Join("; ", template.Messages)}");
                    _cache[name] = template;
                }

                var globals = new ScriptObject();
                globals.Import(new { m = module, e = entity }, renamer: member => member.Name);
                var context = new TemplateContext { MemberRenamer = member => member.Name, StrictVariables = true };
                context.PushGlobal(globals);
                var text = template.Render(context);
                return NormalizeWhitespace(text);
            }

            /// <summary>Şablon kontrol satırlarından kalan boşlukları temizler; satır sonu LF, sonda tek satır sonu.</summary>
            private static string NormalizeWhitespace(string text)
            {
                var lines = text.Replace("\r\n", "\n").Split('\n').Select(l => l.TrimEnd()).ToList();
                var result = new List<string>();
                for (var i = 0; i < lines.Count; i++)
                {
                    var line = lines[i];
                    if (line.Length == 0)
                    {
                        // Ardışık boş satır, '{' sonrası ve '}' öncesi boş satır atılır
                        var prev = result.Count > 0 ? result[^1].TrimStart() : "";
                        var next = lines.Skip(i + 1).FirstOrDefault(l => l.Length > 0)?.TrimStart() ?? "";
                        if (prev.Length == 0 || prev.EndsWith('{') || next.StartsWith('}'))
                            continue;
                    }
                    result.Add(line);
                }
                while (result.Count > 0 && result[^1].Length == 0) result.RemoveAt(result.Count - 1);
                while (result.Count > 0 && result[0].Length == 0) result.RemoveAt(0);
                return string.Join("\n", result) + "\n";
            }
        }
    }
}
